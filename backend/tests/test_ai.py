def test_installed_sdk_serializes_current_model_and_schema_without_network(monkeypatch):
    """Real SDK request serialization, intercepted before any network IO."""
    import json
    from google import genai
    real_client = genai.Client
    requests = []
    monkeypatch.setattr(settings, 'gemini_api_key', SecretStr('offline-fake-key'))

    def respond(request):
        requests.append(request)
        return httpx.Response(200, json={'candidates': [{'content': {
            'role': 'model', 'parts': [{'text': demo_analysis(EVIDENCE).model_dump_json()}]
        }, 'finishReason': 'STOP'}]})

    def offline_client(**kwargs):
        assert kwargs['vertexai'] is False
        assert kwargs['http_options'].retry_options.attempts == 1
        kwargs['http_options'].httpx_client = httpx.Client(
            transport=httpx.MockTransport(respond), trust_env=False)
        return real_client(**kwargs)

    monkeypatch.setattr(genai, 'Client', offline_client)
    result = GeminiProvider().analyze(EVIDENCE)
    assert result == demo_analysis(EVIDENCE)
    assert len(requests) == 1
    request = requests[0]
    assert request.url.path.endswith(f'/models/{settings.gemini_model}:generateContent')
    assert request.url.host == 'generativelanguage.googleapis.com'
    body = json.loads(request.content)
    config = body['generationConfig']
    assert config['responseMimeType'] == 'application/json'
    assert set(body) == {'contents', 'systemInstruction', 'generationConfig'}
    assert set(config) == {'temperature', 'maxOutputTokens', 'responseMimeType', 'responseSchema'}
    assert config['temperature'] == 0
    assert config['maxOutputTokens'] == 1800
    schema = config['responseSchema']

    def validate_legacy_schema(node):
        # Developer API's legacy Schema has no additionalProperties field.
        # A successful MockTransport reply alone never caught this wire error.
        assert 'additional_properties' not in node
        assert 'additionalProperties' not in node
        for child in node.get('properties', {}).values():
            validate_legacy_schema(child)
        if 'items' in node:
            validate_legacy_schema(node['items'])

    validate_legacy_schema(schema)
    assert schema['required'] == ['hypotheses', 'uncertainty']
    hypothesis = schema['properties']['hypotheses']['items']
    assert hypothesis['required'] == ['possible_cause', 'evidence_ids', 'recommended_checks', 'confidence']
    assert hypothesis['properties']['confidence']['enum'] == ['low', 'medium', 'high']
    assert schema['properties']['hypotheses']['max_items'] == 5
    assert hypothesis['properties']['evidence_ids']['max_items'] == 20
    assert hypothesis['properties']['possible_cause']['max_length'] == 600
    assert json.loads(body['contents'][0]['parts'][0]['text']) == EVIDENCE


@pytest.mark.parametrize('invalid', ['root_extra', 'hypothesis_extra', 'long_text', 'too_many_hypotheses', 'invalid_confidence'])
def test_provider_still_enforces_strict_local_contract(provider, invalid):
    import json
    result = demo_analysis(EVIDENCE).model_dump()
    if invalid == 'root_extra':
        result['unexpected'] = 'private-response'
    elif invalid == 'hypothesis_extra':
        result['hypotheses'][0]['unexpected'] = 'private-response'
    elif invalid == 'long_text':
        result['hypotheses'][0]['possible_cause'] = 'x' * 601
    elif invalid == 'too_many_hypotheses':
        result['hypotheses'] *= 6
    else:
        result['hypotheses'][0]['confidence'] = 'certain'
    provider.return_value.text = json.dumps(result)
    with pytest.raises(HTTPException) as exc:
        GeminiProvider().analyze(EVIDENCE)
    assert exc.value.status_code == 502
    assert exc.value.detail == 'Gemini returned an invalid analysis.'
