@pytest.mark.parametrize('status,reason,category', [
    (400, 'API_KEY_INVALID', 'invalid_credentials'),
    (400, 'API_KEY_EXPIRED', 'invalid_credentials'),
    (401, None, 'invalid_credentials'),
    (403, None, 'permission_denied'),
    (404, None, 'model_not_found'),
    (429, None, 'quota_exceeded'),
    (408, None, 'timeout'),
    (504, None, 'timeout'),
    (500, None, 'temporary_provider_failure'),
    (503, None, 'temporary_provider_failure'),
    (400, None, 'invalid_request'),
])
def test_provider_diagnostics_are_classified_without_sensitive_details(provider, caplog, status, reason, category):
    private = 'private-key Authorization: Bearer private-header incident-private-message'
    provider.side_effect = errors.APIError(status, {'error': {
        'message': private, 'status': private,
        'details': [{'reason': reason, 'metadata': {'key': private}}],
    }})
    with caplog.at_level('WARNING', logger='app.services.ai_providers'):
        with pytest.raises(HTTPException) as exc:
            GeminiProvider().analyze(EVIDENCE)
    assert exc.value.status_code == (429 if status == 429 else 502)
    assert private not in exc.value.detail
    records = [r for r in caplog.records if r.name == 'app.services.ai_providers']
    assert len(records) == 1
    record = records[0]
    assert f'status={status}' in record.getMessage()
    assert f'category={category}' in record.getMessage()
    assert f'model={settings.gemini_model}' in record.getMessage()
    assert 'private' not in record.getMessage()
    assert EVIDENCE[0]['id'] not in record.getMessage()
    assert record.exc_info is None


